"""`requirements.md`: a generated, read-only view of `requirements.yaml` (ARCHITECTURE §6.1).

Built in code rather than from a template, because answers can hold model or file text (T2) and
templates render such text only inside `untrusted` blocks, which belong in prompts, not in
artifacts. The state store sanitizes and redacts the result when it writes it.
"""

from aipm.domain.coverage import WEIGHTS
from aipm.domain.models import Answer, Dimension, RequirementsDoc

_TITLES = {
    Dimension.PROBLEM_GOALS: "Problem and goals",
    Dimension.USERS_PERSONAS: "Users and personas",
    Dimension.CORE_FEATURES: "Core features",
    Dimension.DATA: "Data",
    Dimension.INTEGRATIONS: "Integrations",
    Dimension.SCALE_PERFORMANCE: "Scale and performance",
    Dimension.SECURITY_COMPLIANCE: "Security and compliance",
    Dimension.DEPLOYMENT_OPS: "Deployment and operations",
    Dimension.CONSTRAINTS: "Constraints",
    Dimension.SUCCESS_METRICS: "Success metrics",
}


def dimension_title(dimension: Dimension) -> str:
    """A readable name for a checklist dimension."""
    return _TITLES[dimension]


def _indent(text: str) -> str:
    return "\n".join(f"  {line}" if line else "" for line in text.strip().splitlines())


def _source(answer: Answer) -> str:
    if answer.source.value == "file":
        return "from file, confirmed" if answer.confirmed else "from file, not confirmed"
    return answer.source.value


def _header(doc: RequirementsDoc) -> list[str]:
    out: list[str] = [f"# Requirements: {doc.project.name}", ""]
    if doc.project.one_liner:
        out += [doc.project.one_liner, ""]
    out += [
        "Generated by aipm from `requirements.yaml`; do not edit by hand. "
        "Change an answer with `aipm discover --edit Q-ID`.",
        "",
        f"Mode: {doc.mode.value}. Coverage: {doc.coverage.score:.2f} after "
        f"{doc.coverage.rounds} round{'s' if doc.coverage.rounds != 1 else ''}.",
        "",
        "| Dimension | Weight | Score |",
        "|---|---|---|",
    ]
    for dim in Dimension:
        score = doc.coverage.by_dimension.get(dim, 0.0)
        out.append(f"| {dimension_title(dim)} | {WEIGHTS[dim]} | {score:.2f} |")
    return out


def _answers(doc: RequirementsDoc) -> list[str]:
    out = ["", "## Answers", ""]
    if not doc.answers:
        out += ["_None yet._", ""]
    for dim in Dimension:
        answers = [a for a in doc.answers if a.dimension is dim]
        if not answers:
            continue
        out += [f"### {dimension_title(dim)}", ""]
        for answer in answers:
            out.append(f"- **{answer.id}** ({_source(answer)}): {answer.question}")
            out.append(_indent(answer.answer))
        out.append("")
    return out


def _section(title: str, lines: list[str]) -> list[str]:
    return [f"## {title}", "", *(lines or ["_None._"]), ""]


def render_requirements_md(doc: RequirementsDoc) -> str:
    """The Markdown view, deterministic for a given document."""
    assumptions = [
        f"- **{a.id}** ({dimension_title(a.dimension)}, "
        f"{'confirmed' if a.confirmed else 'unconfirmed'}): {a.statement}"
        + (f" Reason: {a.reason}." if a.reason else "")
        for a in doc.assumptions
    ]
    open_questions = [
        f"- **{q.id}** ({dimension_title(q.dimension)}{', blocking' if q.blocking else ''}): "
        f"{q.question}"
        for q in doc.open_questions
    ]
    sources = [
        f"- {s.kind.value}"
        + (f" `{s.path}` (sha256 {s.sha256[:12]})" if s.path and s.sha256 else "")
        for s in doc.sources
    ]
    out = _header(doc) + _answers(doc)
    out += _section("Assumptions", assumptions)
    out += _section("Open questions", open_questions)
    out += _section("Sources", sources)
    return "\n".join(out)
