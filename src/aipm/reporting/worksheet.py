"""`worksheet.md`: a generated, read-only view of `tasks.yaml` (ARCHITECTURE §6.1).

Built in code, like `requirements.md`: titles, descriptions and criteria are model text (T2
until G3), so they are rendered as plain Markdown content, with table cells flattened and pipes
escaped. The state store sanitizes and redacts the result when it writes it.
"""

from collections import Counter

from aipm.domain.models import Task, TasksDoc, TaskSize, TaskStatus

WORKSHEET_FILE = "worksheet.md"


def cell(text: str) -> str:
    """One Markdown table cell: a single line, with pipes escaped."""
    return " ".join(text.split()).replace("|", "\\|")


def _status_counts(tasks: list[Task]) -> str:
    counts = Counter(t.status for t in tasks)
    return ", ".join(f"{s.value.replace('_', ' ')} {counts[s]}" for s in TaskStatus)


def _size_counts(tasks: list[Task]) -> str:
    counts = Counter(t.size for t in tasks)
    return ", ".join(f"{s.value} {counts[s]}" for s in TaskSize)


def _table(tasks: list[Task]) -> list[str]:
    rows = ["| ID | Status | Type | Size | Depends on | Title |", "|---|---|---|---|---|---|"]
    for t in tasks:
        deps = ", ".join(t.depends_on) or "-"
        rows.append(
            f"| {t.id} | {t.status.value} | {t.type.value} | {t.size.value} | {deps} "
            f"| {cell(t.title)} |"
        )
    return rows


def _listed(values: list[str], *, code: bool = False) -> str:
    if not values:
        return "none"
    return ", ".join(f"`{v}`" if code else v for v in values)


def _task(t: Task) -> list[str]:
    deps = [f"{d.ecosystem.value}:{d.name}" for d in t.deps_add]
    lines = [
        f"## {t.id}: {cell(t.title)}",
        "",
        f"- Status: {t.status.value} · Type: {t.type.value} · Size: {t.size.value}",
        f"- Traces: {_listed(t.traces)}",
        f"- Depends on: {_listed(t.depends_on)}",
        f"- Owns: {_listed(t.owns_files, code=True)}",
        f"- Reads: {_listed(t.reads_files, code=True)}",
        f"- Gates: {_listed(t.gates)}",
        f"- New dependencies: {_listed(deps)}",
    ]
    if t.blocked is not None:
        question = f"; question: {cell(t.blocked.question)}" if t.blocked.question else ""
        lines.append(f"- Blocked: {t.blocked.reason.value}{question}")
    if t.description.strip():
        lines.extend(["", t.description.strip()])
    lines.extend(["", "Acceptance criteria:", ""])
    done = "x" if t.status is TaskStatus.DONE else " "
    lines.extend(f"- [{done}] {c.id}: {cell(c.text)}" for c in t.acceptance)
    return lines


def render_worksheet(doc: TasksDoc) -> str:
    """Render `worksheet.md`: a summary, the task table, then one section per task."""
    tasks = sorted(doc.tasks, key=lambda t: t.id)
    lines = [
        "# Worksheet",
        "",
        "Generated by aipm from `.pm/tasks.yaml`. Do not edit it: change the plan with "
        "`aipm plan`.",
        "",
        "## Summary",
        "",
        f"- Tasks: {len(tasks)} ({_status_counts(tasks)})",
        f"- Sizes: {_size_counts(tasks)}",
        "",
        "## Tasks",
        "",
        *_table(tasks),
    ]
    for t in tasks:
        lines.extend(["", *_task(t)])
    return "\n".join(lines) + "\n"
