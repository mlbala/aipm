"""Managed blocks between aipm markers (ARCHITECTURE §10.2).

aipm owns only the text between `<!-- aipm:begin … -->` and `<!-- aipm:end -->`. Everything
before the begin marker and after the end marker is kept byte for byte, line endings included.
A document without markers gets the block appended.

Markers are found loosely (`<!--`, any spacing, any case, then `aipm:begin` or `aipm:end`), so
a near miss is never mistaken for ordinary text. The document must then hold exactly one begin
and one end marker, in that order, each on a line of its own, in the exact form aipm writes.
Anything else is `MalformedBlock` (exit 2) and nothing is written: aipm never guesses which part
of a hand-edited file it may replace.
"""

import re
from dataclasses import dataclass

from aipm.domain.errors import PolicyViolation, UsageError

BEGIN = "<!-- aipm:begin (generated by aipm sync-context; edits inside are overwritten) -->"
END = "<!-- aipm:end -->"

_LOOSE = re.compile(r"<!--\s*aipm\s*:\s*(begin|end)", re.IGNORECASE)
_BEGIN_LINE = re.compile(r"<!-- aipm:begin(?: [^\r\n]*)? -->")
_HINT = (
    "Fix the aipm markers by hand: keep exactly one `<!-- aipm:begin … -->` line and one "
    "`<!-- aipm:end -->` line, in that order and each on its own line, or remove both."
)


class MalformedBlock(UsageError):
    """The aipm markers in a file are missing a partner, repeated, out of order or altered."""

    code = "MALFORMED_BLOCK"


@dataclass(frozen=True, slots=True)
class BlockSpan:
    """Where the managed block sits in a document (string indices)."""

    begin: int
    """Start of the begin marker line."""
    content_start: int
    """Just after the begin marker line's newline."""
    content_end: int
    """Start of the end marker."""
    end: int
    """Just after the end marker; whatever follows on its line belongs to the user."""
    newline: str
    """The line ending of the begin marker line (`\\n` or `\\r\\n`)."""


def _line(document: str, start: int) -> tuple[str, int]:
    """The line starting at `start` without its line ending, and the index of its `\\n` (or
    the document's end)."""
    stop = document.find("\n", start)
    stop = len(document) if stop < 0 else stop
    return document[start:stop].removesuffix("\r"), stop


def _starts_line(document: str, index: int) -> bool:
    return index == 0 or document[index - 1] == "\n"


def find_block(document: str, *, name: str = "the file") -> BlockSpan | None:
    """Locate the managed block, None if there are no markers; `MalformedBlock` otherwise."""
    found = list(_LOOSE.finditer(document))
    if not found:
        return None
    begins = [m for m in found if m.group(1).lower() == "begin"]
    ends = [m for m in found if m.group(1).lower() == "end"]
    if len(begins) != 1 or len(ends) != 1:
        raise MalformedBlock(
            f"{name} has {len(begins)} aipm begin and {len(ends)} end markers; nothing was written",
            hint=_HINT,
        )
    begin, end = begins[0].start(), ends[0].start()
    if end < begin:
        raise MalformedBlock(
            f"{name}: the aipm end marker comes before the begin marker", hint=_HINT
        )
    begin_line, begin_stop = _line(document, begin)
    if (
        not _starts_line(document, begin)
        or not _BEGIN_LINE.fullmatch(begin_line.rstrip(" \t"))
        or begin_line.count("-->") != 1
        or begin_stop >= len(document)
    ):
        raise MalformedBlock(
            f"{name}: the aipm begin marker is altered or not on its own line", hint=_HINT
        )
    end_line, _ = _line(document, end)
    if not _starts_line(document, end) or end_line.rstrip(" \t") != END:
        raise MalformedBlock(
            f"{name}: the aipm end marker is altered or not on its own line", hint=_HINT
        )
    newline = "\r\n" if document[begin_stop - 1 : begin_stop] == "\r" else "\n"
    return BlockSpan(begin, begin_stop + 1, end, end + len(END), newline)


def extract_block(document: str, *, name: str = "the file") -> str | None:
    """The managed block's content with `\\n` line endings, or None if there is none."""
    span = find_block(document, name=name)
    if span is None:
        return None
    return document[span.content_start : span.content_end].replace("\r\n", "\n")


def _check_content(block: str) -> str:
    if "<!--" in block or "\r" in block:
        # Generated content never holds these: sanitize_for_context removes HTML comments and
        # L1 removes carriage returns. Reaching here is a bug, so fail closed.
        raise PolicyViolation("a generated managed block holds an HTML comment or a CR")
    if block and not block.endswith("\n"):
        block += "\n"
    return block


def replace_block(document: str, block: str, *, name: str = "the file") -> str:
    """Insert or replace the managed block in `document`; text outside it is kept exactly."""
    content = _check_content(block)
    span = find_block(document, name=name)
    if span is None:
        newline = "\r\n" if "\r\n" in document else "\n"
        if not document:
            prefix = ""
        elif document.endswith("\n"):
            prefix = document + newline
        else:
            prefix = document + newline + newline
        body = content.replace("\n", newline)
        return f"{prefix}{BEGIN}{newline}{body}{END}{newline}"
    body = content.replace("\n", span.newline)
    return document[: span.begin] + BEGIN + span.newline + body + END + document[span.end :]
